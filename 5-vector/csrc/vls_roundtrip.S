# vls_roundtrip.s
# 驗證：vle32.v 讀進 VRF，vse32.v 寫回記憶體，資料不變
#
# mem[0x2000..200C] = [10, 20, 30, 40]  (預存來源)
# vle32.v v1, (a0)  →  v1 = [10, 20, 30, 40]
# vse32.v v1, (a1)  →  mem[0x2010..201C] = [10, 20, 30, 40]
#
# 驗證點：mem[0x2010]=10, [0x2014]=20, [0x2018]=30, [0x201C]=40

.section .text
.global _start
_start:
    # ── 準備來源資料 ──────────────────────────────
    li   a0, 0x2000
    li   t0, 10;  sw t0,  0(a0)
    li   t0, 20;  sw t0,  4(a0)
    li   t0, 30;  sw t0,  8(a0)
    li   t0, 40;  sw t0, 12(a0)

    # ── 設 vl=4 ──────────────────────────────────
    vsetvli t0, x0, e32, m1, ta, ma    # vl=4

    # ── Vector Load ───────────────────────────────
    vle32.v  v1, (a0)                  # v1 = [10, 20, 30, 40]

    # ── Vector Store ──────────────────────────────
    li   a1, 0x2010
    vse32.v  v1, (a1)                  # mem[0x2010..] = [10, 20, 30, 40]

loop:
    j loop
