# matmul2x2.s
# 2×2 int32 矩陣乘法 C = A × B
#
# A (row-major) @ 0x2000:
#   [1, 2]   → mem[0x2000]=1, [0x2004]=2
#   [3, 4]   → mem[0x2008]=3, [0x200C]=4
#
# B (col-major，已轉置存放) @ 0x2010:
#   B_col0=[5,7] → mem[0x2010]=5, [0x2014]=7
#   B_col1=[6,8] → mem[0x2018]=6, [0x201C]=8
#
# C = A × B:
#   C[0,0] = [1,2]·[5,7] = 5+14  = 19  → mem[0x2020]
#   C[0,1] = [1,2]·[6,8] = 6+16  = 22  → mem[0x2024]
#   C[1,0] = [3,4]·[5,7] = 15+28 = 43  → mem[0x2028]
#   C[1,1] = [3,4]·[6,8] = 18+32 = 50  → mem[0x202C]
#
# 策略：vl=2，每次 vmul.vv 做一個 dot product 的逐元素乘，
#        再用 scalar lw+add 做橫向累加（因為無 vredsum 指令）
#
# 驗證點：mem[0x2020..202C] = [19, 22, 43, 50]

.section .text
.global _start
_start:
    # ── 存 A (row-major) ──────────────────────────
    li   a0, 0x2000           # A base
    li   t0, 1;  sw t0,  0(a0)
    li   t0, 2;  sw t0,  4(a0)
    li   t0, 3;  sw t0,  8(a0)
    li   t0, 4;  sw t0, 12(a0)

    # ── 存 B (col-major / 轉置) ───────────────────
    li   a1, 0x2010           # B_col base
    li   t0, 5;  sw t0,  0(a1)    # B_col0[0]
    li   t0, 7;  sw t0,  4(a1)    # B_col0[1]
    li   t0, 6;  sw t0,  8(a1)    # B_col1[0]
    li   t0, 8;  sw t0, 12(a1)    # B_col1[1]

    # ── 暫存區（vmul 結果用）@ 0x2040 ────────────
    li   s0, 0x2040

    # ── 設 vl=2（2×2矩陣每次只算 2 個元素）────────
    li   t1, 2
    vsetvli t0, t1, e32, m1, ta, ma    # vl=2

    li   a2, 0x2020           # C base
    li   a3, 0x2018           # B_col1 base = a1+8

    # ────────────────────────────────────────────
    # C[0,0] = A_row0 · B_col0
    #        = [1,2] · [5,7] = 5+14 = 19
    # ────────────────────────────────────────────
    vle32.v  v1, (a0)          # v1 = [1, 2]   (A_row0, vl=2)
    vle32.v  v2, (a1)          # v2 = [5, 7]   (B_col0)
    vmul.vv  v3, v1, v2        # v3 = [5, 14]
    vse32.v  v3, (s0)          # 暫存 v3 到 0x2040
    lw   t2,  0(s0)            # t2 = 5
    lw   t3,  4(s0)            # t3 = 14
    add  t2, t2, t3            # t2 = 19
    sw   t2,  0(a2)            # C[0,0] = 19

    # ────────────────────────────────────────────
    # C[0,1] = A_row0 · B_col1
    #        = [1,2] · [6,8] = 6+16 = 22
    # ────────────────────────────────────────────
    # v1 已有 [1,2]，不需重新 load
    vle32.v  v2, (a3)          # v2 = [6, 8]   (B_col1 @ 0x2018)
    vmul.vv  v3, v1, v2        # v3 = [6, 16]
    vse32.v  v3, (s0)
    lw   t2,  0(s0)            # t2 = 6
    lw   t3,  4(s0)            # t3 = 16
    add  t2, t2, t3            # t2 = 22
    sw   t2,  4(a2)            # C[0,1] = 22

    # ────────────────────────────────────────────
    # C[1,0] = A_row1 · B_col0
    #        = [3,4] · [5,7] = 15+28 = 43
    # ────────────────────────────────────────────
    addi a4, a0, 8             # A_row1 base = 0x2008
    vle32.v  v1, (a4)          # v1 = [3, 4]   (A_row1)
    vle32.v  v2, (a1)          # v2 = [5, 7]   (B_col0)
    vmul.vv  v3, v1, v2        # v3 = [15, 28]
    vse32.v  v3, (s0)
    lw   t2,  0(s0)            # t2 = 15
    lw   t3,  4(s0)            # t3 = 28
    add  t2, t2, t3            # t2 = 43
    sw   t2,  8(a2)            # C[1,0] = 43

    # ────────────────────────────────────────────
    # C[1,1] = A_row1 · B_col1
    #        = [3,4] · [6,8] = 18+32 = 50
    # ────────────────────────────────────────────
    # v1 已有 [3,4]，不需重新 load
    vle32.v  v2, (a3)          # v2 = [6, 8]   (B_col1)
    vmul.vv  v3, v1, v2        # v3 = [18, 32]
    vse32.v  v3, (s0)
    lw   t2,  0(s0)            # t2 = 18
    lw   t3,  4(s0)            # t3 = 32
    add  t2, t2, t3            # t2 = 50
    sw   t2, 12(a2)            # C[1,1] = 50

loop:
    j loop
